// 中国法定节假日判断（仅用于「日历价格」批量生成时套用「节假日价」）
//
// ⚠️ 说明：法定节假日与调休安排每年由官方公布，存在变动。
//    此处为静态表，如与当年官方安排不一致，请直接在本文件维护；
//    后续若后端下发节假日列表，可替换本文件实现，调用方无需改动。
//
// 用法：
//   import { isHolidayCN } from '@/utils/holidays.js'
//   isHolidayCN('2026-10-01') // true

// 法定节假日（放假日期，套用节假日价）
const HOLIDAYS_2026 = new Set([
  // 元旦
  '2026-01-01',
  // 春节
  '2026-02-15', '2026-02-16', '2026-02-17', '2026-02-18',
  '2026-02-19', '2026-02-20', '2026-02-21',
  // 清明
  '2026-04-04', '2026-04-05', '2026-04-06',
  // 劳动节
  '2026-05-01', '2026-05-02', '2026-05-03', '2026-05-04', '2026-05-05',
  // 端午
  '2026-06-19', '2026-06-20', '2026-06-21',
  // 中秋
  '2026-09-25', '2026-09-26', '2026-09-27',
  // 国庆
  '2026-10-01', '2026-10-02', '2026-10-03', '2026-10-04',
  '2026-10-05', '2026-10-06', '2026-10-07'
])

// 调休补班日（虽落在周末，但按工作日/平时价处理）
const WORKDAYS_2026 = new Set([
  '2026-02-14', '2026-02-28',
  '2026-05-09',
  '2026-09-19', '2026-10-10'
])

/**
 * 是否为（放假的）法定节假日
 * @param {string} dateStr - 'YYYY-MM-DD'
 * @returns {boolean}
 */
export function isHolidayCN(dateStr) {
  if (!dateStr) return false
  return HOLIDAYS_2026.has(String(dateStr).slice(0, 10))
}

/**
 * 是否为调休补班日（周末但需上班）
 * @param {string} dateStr - 'YYYY-MM-DD'
 * @returns {boolean}
 */
export function isWorkdayMakeup(dateStr) {
  if (!dateStr) return false
  return WORKDAYS_2026.has(String(dateStr).slice(0, 10))
}
